"""Generate native area and RoomSanity reward tables from the client room catalog."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

WORLD = Path(__file__).resolve().parents[1]
AREA_IDS = dict(zip((
    "RAINBOW_ROUTE", "MOONLIGHT_MANSION", "CABBAGE_CAVERN", "MUSTARD_MOUNTAIN",
    "CARROT_CASTLE", "OLIVE_OCEAN", "PEPPERMINT_PALACE", "RADISH_RUINS", "CANDY_CONSTELLATION",
), range(1, 10)))
REGION = re.compile(r"^REGION_([A-Z_]+)/ROOM_[A-Z0-9_]+$")
NATIVE_VISIT_ENTRIES = 288


def generate() -> str:
    rooms = json.loads((WORLD / "data/regions/rooms.json").read_text(encoding="utf-8"))
    areas = [0] * NATIVE_VISIT_ENTRIES
    kinds = [0] * NATIVE_VISIT_ENTRIES
    for region, room in rooms.items():
        meta = room.get("room_sanity")
        if not isinstance(meta, dict):
            locations = room.get("locations")
            meta = locations.get("room_sanity") if isinstance(locations, dict) else None
        if not isinstance(meta, dict) or meta.get("bit_index") is None:
            continue
        match = REGION.match(region)
        area = AREA_IDS.get(match[1], 0) if match else 0
        if not area:
            continue
        index = int(meta["bit_index"])
        if not 0 <= index < NATIVE_VISIT_ENTRIES or areas[index]:
            raise ValueError(f"Duplicate or invalid native visit index {index}: {region}")
        areas[index] = area
        if meta.get("included"):
            kinds[index] = 2 if meta.get("core_landmark") else 1
    def array(name: str, values: list[int]) -> list[str]:
        return [
            f'static const uint8_t {name}[AP_VISIT_ENTRY_COUNT] __attribute__((section(".apvisitdata"))) = {{',
            *("    " + ", ".join(f"{v}u" for v in values[i:i + 16]) + ","
              for i in range(0, len(values), 16)),
            "};",
        ]

    return "\n".join([
        "/* Generated by tools/generate_visit_reward_art_rooms.py. */",
        *array("ap_visit_areas", areas),
        *array("ap_visit_room_kinds", kinds), "",
    ])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    out = WORLD / "kirby_ap_payload/generated_visit_reward_art_rooms.inc"
    expected = generate()
    if args.check:
        if out.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Out of date: {out}")
    else:
        out.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()

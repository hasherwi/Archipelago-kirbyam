"""Generate the exact USA Goal Game origin lookup; no ROM bytes are embedded."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

WORLD = Path(__file__).resolve().parents[1]


def render() -> str:
    rows = json.loads((WORLD / 'data/goal_game_doors.json').read_text())['goals']
    lines = ['/* Generated by tools/generate_goal_game_doors.py; do not edit. */',
             'static const struct ApGoalDoor ap_goal_doors[] = {']
    for row in rows:
        for door in row['doors']:
            lines.append(f"    {{0x{0x08000000 + door['rom_offset']:08X}u, "
                         f"{row['source_room']}u, {door['destination_room']}u, {row['bit_index']}u}},")
    return '\n'.join(lines + ['};', ''])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = WORLD / 'kirby_ap_payload/generated_goal_game_doors.inc'
    content = render()
    if args.check:
        if target.read_text() != content:
            raise SystemExit('Goal Game door lookup is stale')
    else:
        target.write_text(content)


if __name__ == '__main__':
    main()

"""Generate bounded native palette tables from the shared validated registry."""
import importlib.util
import json
from pathlib import Path
import sys

WORLD = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("kirby_color_registry", WORLD / "color_registry.py")
registry = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = registry
spec.loader.exec_module(registry)

def render():
    colors = registry.parse_color_catalog(json.loads((WORLD / "data/colors.json").read_text()))
    lines = ["/* Generated by generate_colors.py; edit data/colors.json instead. */",
             "#ifndef KIRBYAM_COLOR_TABLES_H", "#define KIRBYAM_COLOR_TABLES_H",
             f"#define AP_COLOR_COUNT {len(colors)}u", "#ifdef AP_COLOR_INCLUDE_PALETTES",
             "static const uint16_t ap_color_palettes[][3][16] = {"]
    for color in colors[14:]:
        lines.append("  { /* " + color.display_name + " */")
        lines.extend("    {" + ", ".join(f"0x{x:04X}" for x in row) + "}," for row in color.palettes)
        lines.append("  },")
    return "\n".join(lines + ["};", "#endif", "#endif", ""])

if __name__ == "__main__":
    path = Path(__file__).with_name("color_tables.h")
    result = render()
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != result:
            raise SystemExit("Stale color_tables.h; run generate_colors.py")
    else:
        path.write_text(result)

"""Encode the supplied six gems as four native 4bpp OBJ tiles (Pillow required for regeneration)."""

from colorsys import rgb_to_hsv
from importlib import import_module
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent / "dev-docs" / "chest_reward_art.png"
HEADER = ROOT / "chest_reward_art.h"
PREVIEW = ROOT.parent / "dev-docs" / "chest_reward_art_gba.png"
# Stock in-game OBJ bank F, loaded by sub_0803E050 from palette 42.
NATIVE_COLORS = (0x5EA0, 0x7E80, 0x00D2, 0x01B8, 0x02FE, 0x08BF, 0x025F, 0x0000,
                 0x6E9F, 0x7D40, 0x7FA0, 0x1C96, 0x393B, 0x1262, 0x7FFF, 0x03FF)


def palette_index(pixel: tuple[int, int, int, int]) -> int:
    r, g, b, a = pixel
    h, s, v = rgb_to_hsv(r / 255, g / 255, b / 255)
    if a == 0:
        return 0
    if v < 0.2:
        return 7
    if s < 0.08:
        return 14
    if 0.035 <= h < 0.12:  # Orange
        return 3 if v < 0.8 else 6
    if 0.12 <= h < 0.23:  # Yellow
        return 4 if v < 0.95 else 15
    if 0.23 <= h < 0.55:  # Green
        return 13
    if 0.55 <= h < 0.78:  # Blue
        return 9 if v < 0.86 else 1
    if s < 0.8:  # Pink
        return 12 if v < 0.9 else 8
    return 11 if v < 0.8 else 5  # Red


def main() -> None:
    Image = import_module("PIL.Image")  # Optional, for regenerating developer assets only.
    art = Image.open(SOURCE).convert("RGBA")
    if art.size != (16, 16):
        raise ValueError("Expected the 16×16 source pixel grid")
    indexes = [palette_index(art.getpixel((x, y))) for y in range(16) for x in range(16)]
    # GBA OBJ 1D layout: four 8×8 tiles in row-major order, low nibble first.
    data = bytes(
        indexes[16 * y + x] | indexes[16 * y + x + 1] << 4
        for ty in (0, 8) for tx in (0, 8)
        for y in range(ty, ty + 8) for x in range(tx, tx + 8, 2)
    )
    rows = ("    " + ", ".join(f"0x{n:02X}" for n in data[i:i + 16]) + ","
            for i in range(0, len(data), 16))
    HEADER.write_text(
        "/* Generated by generate_chest_reward_art.py; do not hand edit. */\n"
        "static const uint8_t gApChestRewardArt[AP_SHARD_ART_PADDED_SIZE]\n"
        "__attribute__((used, aligned(4), section(\".apchestart\"))) = {\n"
        + "\n".join(rows) + "\n};\n", encoding="utf-8",
    )
    rendered = Image.new("RGBA", (16, 16))
    rendered.putdata([
        tuple(((NATIVE_COLORS[i] >> c) & 31) * 255 // 31 for c in (0, 5, 10))
        + (255 if i else 0,) for i in indexes
    ])
    rendered.save(PREVIEW, optimize=True)


if __name__ == "__main__":
    main()

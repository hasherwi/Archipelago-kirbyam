"""Encode the supplied trap silhouette in the existing native OBJ palette."""

from importlib import import_module
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent / "dev-docs" / "trap_reward_art.png"
HEADER = ROOT / "trap_reward_art.h"
PREVIEW = ROOT.parent / "dev-docs" / "trap_reward_art_gba.png"


def palette_index(pixel: tuple[int, int, int, int]) -> int:
    # Stretch the source's near-black reds for native 5-bit visibility; leaving
    # bank F alone keeps coincident generic art and other stock sprites correct.
    r, _g, _b, a = pixel
    if a < 200:
        return 0
    if r < 30:
        return 7
    if r < 85:
        return 11
    if r < 102:
        return 12
    return 5


def main() -> None:
    from generate_chest_reward_art import NATIVE_COLORS  # Same native OBJ bank F.

    Image = import_module("PIL.Image")
    art = Image.open(SOURCE).convert("RGBA")
    if art.size != (16, 16):
        raise ValueError("Expected the original 16×16 pixel grid")
    indexes = [palette_index(art.getpixel((x, y))) for y in range(16) for x in range(16)]
    data = bytes(
        indexes[16 * y + x] | indexes[16 * y + x + 1] << 4
        for ty in (0, 8) for tx in (0, 8)
        for y in range(ty, ty + 8) for x in range(tx, tx + 8, 2)
    )
    rows = ("    " + ", ".join(f"0x{n:02X}" for n in data[i:i + 16]) + ","
            for i in range(0, len(data), 16))
    HEADER.write_text(
        "/* Generated by generate_trap_reward_art.py; do not hand edit. */\n"
        "static const uint8_t gApTrapRewardArt[AP_SHARD_ART_PADDED_SIZE]\n"
        "__attribute__((used, aligned(4), section(\".apchestart\"))) = {\n"
        + "\n".join(rows) + "\n};\n", encoding="utf-8",
    )
    rendered = Image.new("RGBA", (16, 16))
    rendered.putdata([
        tuple(((NATIVE_COLORS[i] >> c) & 31) * 255 // 31 for c in (0, 5, 10))
        + (255 if i else 0,) for i in indexes
    ])
    rendered.save(PREVIEW, optimize=True)


if __name__ == "__main__":
    main()

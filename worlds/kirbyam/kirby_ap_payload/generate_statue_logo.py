"""Generate a native 16×16 statue from Archipelago's application icon."""
import hashlib
from pathlib import Path

from PIL import Image

from world_statue_assets import _to_tiles

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "data" / "icon.png"
OUTPUT = Path(__file__).with_name("statue_logo.h")


def render() -> str:
    original = Image.open(SOURCE).convert("RGBA")
    colors = [(*original.getpixel(point)[:3], index) for point, index in
              (((256, 57), 12), ((100, 135), 4), ((405, 135), 13),
               ((73, 313), 1), ((438, 313), 8), ((255, 409), 6))]
    image = original.resize((16, 16), Image.Resampling.BOX)
    # Use one recognizable native OBJ-bank-F color per original island.
    # Direct RGB quantization collapses the red and blue islands to one ink.
    pixels = [min(colors, key=lambda c: (r-c[0])**2 + (g-c[1])**2 + (b-c[2])**2)[3]
              if a >= 128 else 0 for r, g, b, a in image.getdata()]
    data = _to_tiles(pixels)
    rows = ["    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ","
            for i in range(0, len(data), 16)]
    return (
        "/* Generated by generate_statue_logo.py from Archipelago data/icon.png. */\n"
        f"/* Source SHA256: {hashlib.sha256(SOURCE.read_bytes()).hexdigest()} */\n"
        "__attribute__((used, section(\".apstatueart\")))\n"
        "const uint8_t gApWorldStatueLogo[128] = {\n" + "\n".join(rows) + "\n};\n"
    )


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8")
